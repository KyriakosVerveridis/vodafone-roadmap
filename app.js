/* ---------- STATE / RENDER ---------- */
let current = 0;

function visibleSteps(){
  return STEPS.map((s,i)=>({...s,i})).filter(s=> !s.applicable || s.applicable(scenario));
}

function renderScenarioSelect(){
  const el = document.getElementById("scenarioSelect");
  el.innerHTML = "";
  Object.entries(SCENARIOS).forEach(([key,label])=>{
    const b = document.createElement("button");
    b.textContent = label;
    if(key===scenario) b.classList.add("active");
    b.onclick = ()=>{ scenario = key; current = 0; render(); };
    el.appendChild(b);
  });
}

function render(){
  renderScenarioSelect();
  const steps = visibleSteps();
  if(current >= steps.length) current = steps.length - 1;
  if(current < 0) current = 0;
  const step = steps[current];

  document.getElementById("eyebrow").textContent = "Βήμα " + (current+1) + " από " + steps.length;
  document.getElementById("title").textContent = step.name;
  document.getElementById("body").innerHTML = step.content(scenario);
  document.getElementById("stepCounter").textContent = "Βήμα " + (current+1) + " / " + steps.length;
  document.getElementById("stepName").textContent = SCENARIOS[scenario];

  const pct = ((current+1)/steps.length)*100;
  document.getElementById("progressFill").style.width = pct + "%";

  const rail = document.getElementById("rail");
  rail.innerHTML = "";
  steps.forEach((s,idx)=>{
    const seg = document.createElement("div");
    seg.className = "seg" + (idx<current?" done":"") + (idx===current?" current":"");
    seg.onclick = ()=>{ current = idx; render(); };
    rail.appendChild(seg);
  });

  document.getElementById("backBtn").disabled = current===0;
  const nextBtn = document.getElementById("nextBtn");
  if(current === steps.length-1){
    nextBtn.textContent = "Ολοκλήρωση ✓";
  } else {
    nextBtn.textContent = "Επόμενο βήμα →";
  }
}

document.getElementById("backBtn").onclick = ()=>{ if(current>0){ current--; render(); } };
document.getElementById("nextBtn").onclick = ()=>{
  const steps = visibleSteps();
  if(current < steps.length-1){ current++; render(); }
};

document.addEventListener("keydown",(e)=>{
  const overlayOpen = document.getElementById("overlay").classList.contains("open");
  if(overlayOpen) return; // δεν αλλάζει βήμα ενόσω είναι ανοιχτό πάνελ (ενστάσεις/δικαιολογητικά/τιμές)
  if(e.key === "ArrowRight"){ document.getElementById("nextBtn").click(); }
  if(e.key === "ArrowLeft"){ document.getElementById("backBtn").click(); }
});

